def scaled_points(points, width, height):
    return [(round(x * width / 683), round(y * height / 1024)) for x, y in points]


def main():
    PREVIEW_ROOT.mkdir(parents=True, exist_ok=True)
    cards = []
    for name, item in ITEMS.items():
        source_path = ROOT / item["source"]
        image = ImageOps.exif_transpose(Image.open(source_path)).convert("RGBA")
        mask = Image.new("L", image.size, 0)
        draw = ImageDraw.Draw(mask)
        draw.polygon(scaled_points(item["outer"], image.width, image.height), fill=255)
        for hole in item["holes"]:
            draw.polygon(scaled_points(hole, image.width, image.height), fill=0)
        alpha = image.getchannel("A")
        mask = Image.frombytes(
            "L",
            image.size,
            bytes((a * m // 255) for a, m in zip(alpha.tobytes(), mask.tobytes())),
        )
        mask.save(ROOT / item["mask"])
        background = Image.new("RGBA", image.size, (128, 128, 128, 255))
        preview = Image.alpha_composite(background, image)
        tint = Image.new("RGBA", image.size, (30, 210, 140, 0))
        tint.putalpha(mask.point(lambda value: value * 112 // 255))
        preview = Image.alpha_composite(preview, tint).convert("RGB")
        preview.thumbnail((250, 375), Image.Resampling.LANCZOS)
        card = Image.new("RGB", (270, 420), (245, 245, 245))
        card.paste(preview, ((270 - preview.width) // 2, 10))
        ImageDraw.Draw(card).text((10, 395), name, fill=(20, 20, 20))
        card.save(PREVIEW_ROOT / f"{name}-preview.jpg", quality=92)
        cards.append(card)
    sheet = Image.new("RGB", (810, 840), (235, 235, 235))
    for index, card in enumerate(cards):
        sheet.paste(card, ((index % 3) * 270, (index // 3) * 420))
    sheet.save(PREVIEW_ROOT / "all-mask-previews.jpg", quality=92)
    print(f"Created {len(ITEMS)} approximate garment masks.")
    print(f"Review: {PREVIEW_ROOT / 'all-mask-previews.jpg'}")


if __name__ == "__main__":
    main()
